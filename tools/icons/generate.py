#!/usr/bin/env python3
"""Generate the app's icon assets from the Lucide SVG masters.

Masters live in assets/icons/lucide/*.svg and are the single source of truth for
every platform. This script produces the two derived forms that are committed:

  qt-app/resources/icons.qrc + qt-app/resources/icons/lucide/*.png
      16/20/32/64px rasters for the Qt app (no QtSvg needed at build or run time)

  assets/icons/android/drawable/ic_lucide_*.xml
      VectorDrawables for the Android app, from the same path data

Usage:
    python tools/icons/generate.py                 # both, PNG via auto-detected rasteriser
    python tools/icons/generate.py --png-only
    python tools/icons/generate.py --android-only
    python tools/icons/generate.py --rasteriser "out/build/tools/svg2png.exe"

The PNG rasteriser is tools/icons/svg2png.cpp (Qt). If you have rsvg-convert or
Inkscape it uses those instead. PNGs are committed, so CI never rasterises.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape

REPO = Path(__file__).resolve().parents[2]
MASTERS = REPO / "assets" / "icons" / "lucide"
QT_PNG_DIR = REPO / "qt-app" / "resources" / "icons" / "lucide"
QRC = REPO / "qt-app" / "resources" / "icons.qrc"
ANDROID_DIR = REPO / "assets" / "icons" / "android" / "drawable"

PNG_SIZES = (16, 20, 32, 64)


# ---------------------------------------------------------------- PNG (Qt) ----
def rasterise(sizes, explicit: str | None) -> None:
    masters = sorted(MASTERS.glob("*.svg"))
    if not masters:
        sys.exit(f"no SVG masters in {MASTERS}")

    if explicit:
        tool = [explicit]
        out = None
    elif shutil.which("rsvg-convert"):
        tool = ["rsvg-convert"]
        out = None
    else:
        sys.exit(
            "no rasteriser found. Build tools/icons/svg2png.cpp with Qt (see\n"
            "docs/icon-strategy.md) and pass --rasteriser <path>, or install rsvg-convert."
        )

    QT_PNG_DIR.mkdir(parents=True, exist_ok=True)
    for stale in QT_PNG_DIR.glob("*.png"):
        stale.unlink()
    try:
        subprocess.run(tool + [str(MASTERS), str(QT_PNG_DIR)] + [str(s) for s in sizes], check=True)
    except OSError as error:
        sys.exit(f"cannot run {tool[0]}: {error}\n"
                 "A Qt build of svg2png needs Qt's bin directory on PATH.")
    except subprocess.CalledProcessError as error:
        hint = ""
        if error.returncode in (0xC0000135, -1073741515, 3221225781):
            hint = ("\nThat exit code means the Qt DLLs were not found: put the Qt kit's "
                    "bin directory on PATH before running this script.")
        sys.exit(f"{tool[0]} failed with exit code {error.returncode}.{hint}")


def write_qrc(sizes) -> None:
    lines = [
        "<!-- Generated by tools/icons/generate.py - do not edit by hand. -->",
        "<RCC>",
        '    <qresource prefix="/icons/lucide">',
    ]
    # <file> paths are relative to the .qrc, so an alias is what makes the resource
    # path the plain :/icons/lucide/<name>-<size>.png the helper expects.
    for png in sorted(QT_PNG_DIR.glob("*.png")):
        lines.append(f'        <file alias="{png.name}">icons/lucide/{png.name}</file>')
    lines += ["    </qresource>", "</RCC>", ""]
    QRC.write_text("\n".join(lines), encoding="utf-8")
    print(f"{QRC.name}: {len(list(QT_PNG_DIR.glob('*.png')))} files, sizes {sizes}")


# ------------------------------------------------------------- Android --------
_NUM = r"[-+]?[0-9.]+"

def _num(value: str) -> str:
    # VectorDrawable wants bare numbers; Lucide writes them the same way, but trim
    # any trailing ".0" noise so the XML stays small and diff-stable.
    v = float(value)
    return str(int(v)) if v == int(v) else f"{v:g}"


def element_to_pathdata(tag: str, attrs: dict) -> str | None:
    a = attrs
    if tag == "path":
        return a.get("d")
    if tag == "line":
        return f"M{_num(a['x1'])},{_num(a['y1'])} L{_num(a['x2'])},{_num(a['y2'])}"
    if tag == "circle":
        cx, cy, r = _num(a["cx"]), _num(a["cy"]), float(a["r"])
        r = _num(str(r))
        return (f"M{_num(str(float(cx) - float(r)))},{cy} "
                f"a{r},{r} 0 1,0 {_num(str(2 * float(r)))},0 "
                f"a{r},{r} 0 1,0 {_num(str(-2 * float(r)))},0")
    if tag in ("polyline", "polygon"):
        pts = [p for p in re.split(r"[ ,]+", a.get("points", "").strip()) if p]
        if len(pts) < 4:
            return None
        path = f"M{_num(pts[0])},{_num(pts[1])}"
        for i in range(2, len(pts) - 1, 2):
            path += f" L{_num(pts[i])},{_num(pts[i + 1])}"
        return path + (" Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y = float(a.get("x", 0)), float(a.get("y", 0))
        w, h = float(a["width"]), float(a["height"])
        rx = float(a.get("rx", a.get("ry", 0)) or 0)
        if rx <= 0:
            return f"M{_num(str(x))},{_num(str(y))} h{_num(str(w))} v{_num(str(h))} h{_num(str(-w))} Z"
        return (f"M{_num(str(x + rx))},{_num(str(y))} "
                f"h{_num(str(w - 2 * rx))} a{_num(str(rx))},{_num(str(rx))} 0 0,1 {_num(str(rx))},{_num(str(rx))} "
                f"v{_num(str(h - 2 * rx))} a{_num(str(rx))},{_num(str(rx))} 0 0,1 {_num(str(-rx))},{_num(str(rx))} "
                f"h{_num(str(-(w - 2 * rx)))} a{_num(str(rx))},{_num(str(rx))} 0 0,1 {_num(str(-rx))},{_num(str(-rx))} "
                f"v{_num(str(-(h - 2 * rx)))} a{_num(str(rx))},{_num(str(rx))} 0 0,1 {_num(str(rx))},{_num(str(-rx))} Z")
    return None


def to_vector_drawable(svg: str, name: str) -> str | None:
    view = re.search(r'viewBox="([^"]+)"', svg)
    if not view:
        return None
    _, _, vw, vh = [p for p in re.split(r"[ ,]+", view.group(1).strip())]
    stroke = re.search(r'stroke-width="([^"]+)"', svg)
    stroke_width = stroke.group(1) if stroke else "2"

    paths = []
    for tag, raw_attrs in re.findall(r"<(path|line|circle|polyline|polygon|rect)\b([^>]*)>", svg):
        attrs = dict(re.findall(r'([a-zA-Z-]+)="([^"]*)"', raw_attrs))
        d = element_to_pathdata(tag, attrs)
        if d:
            paths.append(d)
    if not paths:
        return None

    body = "\n".join(
        f'    <path\n        android:strokeColor="#FF000000"\n'
        f'        android:strokeWidth="{stroke_width}"\n'
        f'        android:strokeLineCap="round"\n'
        f'        android:strokeLineJoin="round"\n'
        f'        android:pathData="{escape(d)}" />'
        for d in paths
    )
    return (
        f'<!-- Generated by tools/icons/generate.py from assets/icons/lucide/{name}.svg -->\n'
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="24dp"\n'
        f'    android:height="24dp"\n'
        f'    android:viewportWidth="{vw}"\n'
        f'    android:viewportHeight="{vh}">\n'
        f'    <group>\n{body}\n    </group>\n'
        f'</vector>\n'
    )


def write_android() -> None:
    ANDROID_DIR.mkdir(parents=True, exist_ok=True)
    for stale in ANDROID_DIR.glob("*.xml"):
        stale.unlink()
    count = 0
    for svg_path in sorted(MASTERS.glob("*.svg")):
        xml = to_vector_drawable(svg_path.read_text(encoding="utf-8"), svg_path.stem)
        if xml is None:
            print(f"  skipped {svg_path.name}: could not convert")
            continue
        (ANDROID_DIR / f"ic_lucide_{svg_path.stem.replace('-', '_')}.xml").write_text(xml, encoding="utf-8")
        count += 1
    print(f"android: {count} vector drawables -> {ANDROID_DIR.relative_to(REPO)}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--png-only", action="store_true")
    ap.add_argument("--android-only", action="store_true")
    ap.add_argument("--rasteriser", default=None)
    args = ap.parse_args()

    if not args.android_only:
        rasterise(PNG_SIZES, args.rasteriser)
        write_qrc(PNG_SIZES)
    if not args.png_only:
        write_android()


if __name__ == "__main__":
    main()
